  await expect(table.getByRole('columnheader', { name: '资产', exact: true })).toHaveAttribute('aria-sort', 'descending');
  await expect(table.getByRole('columnheader', { name: '合约 OI · 原始值', exact: true })).toHaveCount(0);
  await expect(table.getByRole('textbox')).toHaveValue('');
  await expect(table.getByRole('link', { name: /BTC Bitcoin$/ })).toBeVisible();
  await staleTable.getByRole('combobox', { name: '每页条数 资产行情' }).selectOption('60');
  await expect(staleTable.getByRole('alert')).toContainText('表格配置已更新');
  await expect(staleTable.getByRole('combobox')).toHaveValue('15');
  await staleTable.getByRole('button', { name: '重新读取表格配置 资产行情' }).click();
