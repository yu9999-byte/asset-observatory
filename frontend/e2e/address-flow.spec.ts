import { expect,test } from '@playwright/test';

const address='0x0000000000000000000000000000000000000001';
const counterparty='0x0000000000000000000000000000000000000002';
const envelope=(data:unknown[],nextCursor:string|null=null)=>({data,status:'partial',source:'UI test fixture',sourceUrl:'',fetchedAt:null,sourceAt:null,coverage:'Automated test data only',reason:null,nextCursor});

test('holder preview opens independent address detail in a new tab with source pagination',async({page,context},testInfo)=>{
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
 await context.route('**/api/**',async route=>{
  const url=new URL(route.request().url());
  let data:unknown;
  if(url.pathname==='/api/markets')data={assets:[{id:'JCT',symbol:'JCT',name:'Janction',chain:'ethereum',contract:address,decimals:18}],market:envelope([]),derivatives:envelope([])};
  else if(url.pathname==='/api/workspace')data={watches:[],notes:[]};
  else if(url.pathname.includes('/table-preferences'))data={hidden:[],order:[],sortKey:null,desc:false,pageSize:15,version:0};
  else if(url.pathname.endsWith('/holders'))data=envelope([{address,balance:'100',rawBalance:'100',decimals:0,isContract:true}]);
  else if(url.pathname.endsWith('/liquidations'))data=envelope([]);
  else if(url.pathname.endsWith('/transfers')){
   const next=url.searchParams.has('cursor');
   data=envelope((next?[{amount:'5',direction:'IN'}]:[{amount:'10',direction:'IN'},{amount:'20',direction:'OUT'},{amount:'30',direction:'SELF'}]).map((row,i)=>({...row,id:String(i),from:row.direction==='IN'?counterparty:address,to:row.direction==='OUT'?counterparty:address,hash:'0x'+String(i+1).padStart(64,'0'),logIndex:i,blockNumber:100+i,sourceAt:'2026-10-22T08:00:00Z'})),next?null:'next-page');
  }else throw new Error('Unexpected API '+url.pathname);
  await route.fulfill({json:data});
 });
 await page.goto('/assets/JCT');
 const holders=page.getByRole('region',{name:'持仓地址',exact:true});
 const trigger=holders.getByRole('button',{name:'查看地址 '+address,exact:true});
 await trigger.click();
 const drawer=page.getByRole('dialog',{name:'转入转出',exact:true});
 await expect(drawer).toBeVisible();
 await expect(page).toHaveURL(/\/assets\/JCT$/);
 await expect(drawer.getByRole('group',{name:'本批次资金流'})).toContainText('净流量-10JCT');
 const close=drawer.getByRole('button',{name:'关闭地址预览',exact:true});
 const detailLink=drawer.getByRole('link',{name:'新页面查看地址详情',exact:true});
 await close.focus();
 await page.keyboard.press('Shift+Tab');
 await expect(detailLink).toBeFocused();
 await page.keyboard.press('Tab');
 await expect(close).toBeFocused();
 await drawer.getByRole('button',{name:'转出',exact:true}).click();
 await expect(drawer.getByText('−20',{exact:true})).toBeVisible();
 await expect(drawer.getByText('+10',{exact:true})).toHaveCount(0);
 await drawer.getByRole('button',{name:'全部',exact:true}).click();
 await page.screenshot({path:testInfo.outputPath('address-drawer.png'),fullPage:true});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 const popupPromise=page.waitForEvent('popup');
 await drawer.getByRole('link',{name:'新页面查看地址详情',exact:true}).click();
 const detailPage=await popupPromise;
 detailPage.on('pageerror',error=>errors.push(error.message));
 await expect(detailPage).toHaveURL(new RegExp('/addresses/'+address+'\\?asset=JCT'));
 await expect(detailPage.getByRole('heading',{name:'地址转账事件',exact:true})).toBeVisible();
 const metrics=detailPage.getByTestId('address-flow-metrics');
 await expect(metrics).toContainText('本批次 净流量-10');
 await expect(metrics).toContainText('本批次转账次数3');
 await expect(detailPage.getByRole('button',{name:'交换',exact:true})).toBeDisabled();
 const transfers=detailPage.getByRole('region',{name:'转账事件',exact:true});
 await expect(transfers.getByText('+10',{exact:false})).toBeVisible();
 await detailPage.getByRole('button',{name:'转出',exact:true}).click();
 await expect(transfers.getByText('−20',{exact:false})).toBeVisible();
 await expect(transfers.getByText('+10',{exact:false})).toHaveCount(0);
 await expect(metrics).toContainText('本批次 净流量-10');
 await detailPage.getByRole('button',{name:'全部转账',exact:true}).click();
 await detailPage.screenshot({path:testInfo.outputPath('address-flow.png'),fullPage:true});
 expect(await detailPage.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 await detailPage.getByRole('button',{name:'下一批',exact:true}).click();
 await expect(metrics).toContainText('本批次 净流量5');
 await expect(metrics).toContainText('本批次转账次数1');
 await detailPage.getByRole('button',{name:'7D',exact:true}).click();
 await expect(detailPage.getByText('统计窗口未完整覆盖',{exact:true})).toBeVisible();
 await expect(metrics).toContainText('7D 累计转入—');
 await detailPage.reload();
 await expect(detailPage.getByRole('combobox',{name:'事件代币'})).toHaveValue('JCT');
 await detailPage.close();
 await page.keyboard.press('Escape');
 await expect(drawer).toHaveCount(0);
 await expect(trigger).toBeFocused();
 expect(errors).toEqual([]);
});
